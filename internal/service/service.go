// Package service sets up the daemon as a systemd user service (`ade install-service`).
//
// The unit starts `ade serve` with a fixed configuration. Because systemd user services do not
// inherit the shell's environment, the unit takes over the current PATH (git, docker, gh,
// claude, codex). Secrets do not belong in the unit but in the configuration.
package service

import (
	"bufio"
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// Name is the name of the unit.
const Name = "ade.service"

// configMarker is a comment in the unit naming the configuration it starts with.
const configMarker = "# ade-config: "

// ErrNoSystemd means that no systemd user manager is reachable.
var ErrNoSystemd = errors.New("systemd is not available")

// Runner runs systemctl and returns the combined output.
type Runner func(ctx context.Context, args ...string) ([]byte, error)

// Manager installs and removes the unit.
type Manager struct {
	// UnitDir is the directory of the user units (default: $XDG_CONFIG_HOME/systemd/user).
	UnitDir string
	// Exe is the absolute path of the ade binary.
	Exe string
	// ConfigPath is the absolute path of the configuration.
	ConfigPath string
	// LogPath is the daemon log; stdout and stderr go there.
	LogPath string
	// Path is the PATH of the service.
	Path string
	// Run runs systemctl (default: real systemctl).
	Run Runner
}

// New creates a manager with default values for the current user.
func New(configPath, logPath string) (*Manager, error) {
	exe, err := os.Executable()
	if err != nil {
		return nil, err
	}
	if exe, err = filepath.EvalSymlinks(exe); err != nil {
		return nil, err
	}
	dir, err := DefaultUnitDir()
	if err != nil {
		return nil, err
	}
	return &Manager{
		UnitDir:    dir,
		Exe:        exe,
		ConfigPath: configPath,
		LogPath:    logPath,
		Path:       os.Getenv("PATH"),
		Run:        systemctl,
	}, nil
}

// DefaultUnitDir returns $XDG_CONFIG_HOME/systemd/user or ~/.config/systemd/user.
func DefaultUnitDir() (string, error) {
	base := os.Getenv("XDG_CONFIG_HOME")
	if base == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			return "", err
		}
		base = filepath.Join(home, ".config")
	}
	return filepath.Join(base, "systemd", "user"), nil
}

func systemctl(ctx context.Context, args ...string) ([]byte, error) {
	return exec.CommandContext(ctx, "systemctl", append([]string{"--user"}, args...)...).CombinedOutput()
}

// UnitPath is the path of the unit file.
func (m *Manager) UnitPath() string { return filepath.Join(m.UnitDir, Name) }

// Unit returns the contents of the unit file.
func (m *Manager) Unit() string {
	var b strings.Builder
	b.WriteString("# Generated by `ade install-service`; remove with `ade uninstall-service`.\n")
	b.WriteString(configMarker + m.ConfigPath + "\n")
	b.WriteString("[Unit]\n")
	b.WriteString("Description=ADE – control center for AI agents\n")
	b.WriteString("\n[Service]\n")
	b.WriteString("Type=simple\n")
	fmt.Fprintf(&b, "ExecStart=%s serve --config %s\n", quote(m.Exe), quote(m.ConfigPath))
	if m.Path != "" {
		// In Environment= systemd replaces no variables, only specifiers.
		fmt.Fprintf(&b, "Environment=%s\n", quoteEnv("PATH="+m.Path))
	}
	if m.LogPath != "" {
		// append: exists since systemd 240 (Ubuntu 20.04 and later).
		fmt.Fprintf(&b, "StandardOutput=append:%s\n", escape(m.LogPath))
		fmt.Fprintf(&b, "StandardError=append:%s\n", escape(m.LogPath))
	}
	b.WriteString("Restart=on-failure\n")
	b.WriteString("RestartSec=5\n")
	b.WriteString("\n[Install]\n")
	b.WriteString("WantedBy=default.target\n")
	return b.String()
}

// escape masks specifiers (%) and variables ($) for systemd.
func escape(s string) string {
	return strings.NewReplacer("%", "%%", "$", "$$").Replace(s)
}

// quote puts a value for ExecStart/Environment in double quotes.
func quote(s string) string {
	s = strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(escape(s))
	return `"` + s + `"`
}

// quoteEnv puts a value for Environment in double quotes.
func quoteEnv(s string) string {
	s = strings.NewReplacer(`\`, `\\`, `"`, `\"`, "%", "%%").Replace(s)
	return `"` + s + `"`
}

// Available checks whether the systemd user manager is running.
func (m *Manager) Available(ctx context.Context) error {
	out, err := m.Run(ctx, "show-environment")
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if msg == "" {
			msg = err.Error()
		}
		return fmt.Errorf("%w (%s).\nUnder WSL add to /etc/wsl.conf:\n  [boot]\n  systemd=true\n"+
			"then run `wsl --shutdown` in Windows and reopen WSL", ErrNoSystemd, firstLine(msg))
	}
	return nil
}

// Installed reports whether the unit file exists.
func (m *Manager) Installed() bool {
	_, err := os.Stat(m.UnitPath())
	return err == nil
}

// InstalledConfig returns the configuration the installed unit starts with ("" without a unit).
func (m *Manager) InstalledConfig() string {
	data, err := os.ReadFile(m.UnitPath())
	if err != nil {
		return ""
	}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		if v, ok := strings.CutPrefix(sc.Text(), configMarker); ok {
			return v
		}
	}
	return ""
}

// Active reports whether the service is running.
func (m *Manager) Active(ctx context.Context) bool {
	out, err := m.Run(ctx, "is-active", Name)
	return err == nil && strings.TrimSpace(string(out)) == "active"
}

// Install writes the unit, reloads systemd, and enables and starts the service.
func (m *Manager) Install(ctx context.Context) error {
	if err := m.Available(ctx); err != nil {
		return err
	}
	if err := os.MkdirAll(m.UnitDir, 0o700); err != nil {
		return err
	}
	tmp := m.UnitPath() + ".tmp"
	if err := os.WriteFile(tmp, []byte(m.Unit()), 0o600); err != nil {
		return err
	}
	if err := os.Rename(tmp, m.UnitPath()); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	if err := m.call(ctx, "daemon-reload"); err != nil {
		return err
	}
	// restart instead of start: a changed unit (new binary, other configuration) takes effect right away.
	if err := m.call(ctx, "enable", Name); err != nil {
		return err
	}
	return m.call(ctx, "restart", Name)
}

// Uninstall stops and disables the service and removes the unit.
func (m *Manager) Uninstall(ctx context.Context) error {
	if !m.Installed() {
		return fmt.Errorf("%s is not installed (%s)", Name, m.UnitPath())
	}
	if err := m.Available(ctx); err == nil {
		if err := m.call(ctx, "disable", "--now", Name); err != nil {
			return err
		}
	}
	if err := os.Remove(m.UnitPath()); err != nil {
		return err
	}
	if err := m.Available(ctx); err == nil {
		return m.call(ctx, "daemon-reload")
	}
	return nil
}

// Start starts the installed service.
func (m *Manager) Start(ctx context.Context) error { return m.call(ctx, "start", Name) }

// Stop stops the service; systemctl waits until the daemon has ended.
func (m *Manager) Stop(ctx context.Context) error { return m.call(ctx, "stop", Name) }

// Linger reports whether lingering is active for the user (the user manager then runs without
// an open session). ok is false if this cannot be determined.
func Linger(ctx context.Context) (enabled, ok bool) {
	out, err := exec.CommandContext(ctx, "loginctl", "show-user", fmt.Sprint(os.Getuid()), "--property=Linger", "--value").Output()
	if err != nil {
		return false, false
	}
	return strings.TrimSpace(string(out)) == "yes", true
}

func (m *Manager) call(ctx context.Context, args ...string) error {
	out, err := m.Run(ctx, args...)
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if msg == "" {
			msg = err.Error()
		}
		return fmt.Errorf("systemctl --user %s: %s", strings.Join(args, " "), msg)
	}
	return nil
}

func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		return s[:i]
	}
	return s
}
